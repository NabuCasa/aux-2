"""Write the esp-idf-sbom manifests an older ESPHome build did not.

Usage: write_manifests.py <spec.json>

Writes what esphome/espidf/sbom.py (ESPHome #21454 and later) writes into a
build: the project sbom.yml, src/sbom.yml for ESPHome with each external
component carved out, and an sbom.yml for each converted library. The values
come from the spec, since an older build recorded none of them.
"""

import json
from pathlib import Path
import sys

import yaml

GENERATED = "# Generated by ESPHome\n"


def dump(path: Path, data: dict, header: str = "") -> None:
    path.write_text(header + yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    print(f"wrote {path}")


def purl(url: str, version: str, subpath: str | None = None) -> str:
    owner, repo = url.removeprefix("https://github.com/").removesuffix(".git").split("/")
    return f"pkg:github/{owner}/{repo}@{version}" + (f"#{subpath}" if subpath else "")


def main() -> None:
    spec = json.loads(Path(sys.argv[1]).read_text())
    build = Path(spec["build_dir"])
    project = spec["project"]
    organization = f"Organization: {project['supplier']}"
    dump(
        build / "sbom.yml",
        {
            "name": project["name"],
            "version": project["version"],
            "supplier": f"{organization} ({project['contact']})",
            "document": {
                "manufacturer": {
                    "name": organization,
                    "contact": project["contact"],
                    "url": project["url"],
                }
            },
        },
    )

    esphome = spec["esphome"]
    manifests = []
    for ext in spec["externals"]:
        dest = f"esphome/components/{ext['name']}"
        if not (build / "src" / dest).is_dir():
            sys.exit(f"{dest} is not in the build; check the spec")
        manifests.append(
            {
                "dest": dest,
                "manifest": {
                    "name": ext["name"],
                    "description": ext["description"],
                    "version": ext["commit"],
                    "repository": ext["url"],
                    "purl": purl(ext["url"], ext["commit"], ext["subpath"]),
                },
            }
        )
    dump(
        build / "src" / "sbom.yml",
        {
            "name": "esphome",
            "version": esphome["version"],
            "description": "ESPHome firmware runtime and generated code",
            "supplier": "Organization: Open Home Foundation",
            "license": "GPL-3.0-only",
            "repository": "https://github.com/esphome/esphome",
            "purl": purl("https://github.com/esphome/esphome", esphome["commit"]),
            "manifests": manifests,
        },
    )

    description = json.loads((build / "build" / "project_description.json").read_text())
    for info in description["build_component_info"].values():
        component_dir = Path(info.get("dir", ""))
        library_json = component_dir / "library.json"
        # Registry components describe themselves; only converted libraries need one
        if (
            not library_json.is_file()
            or (component_dir / "sbom.yml").is_file()
            or (component_dir / ".component_hash").is_file()
        ):
            continue
        library = json.loads(library_json.read_text())
        if version := library.get("version"):
            dump(
                component_dir / "sbom.yml",
                {"name": library.get("name") or component_dir.name, "version": version},
                GENERATED,
            )


if __name__ == "__main__":
    main()
